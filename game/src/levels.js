// Parse one level definition into runtime data. Solid tiles become a
// grid of codes (0 empty, 1 solid, 2 crumble); everything else becomes
// an entity placed in pixel space. The grid is rows of Uint8Array.
export function loadLevel(def) {
  const rows = def.map.length;
  const cols = def.map[0].length;
  const grid = [];
  for (let y = 0; y < rows; y++) grid.push(new Uint8Array(cols));
  const coins = [];
  const shards = [];
  const spikes = [];
  const springs = [];
  const checkpoints = [];
  const walkers = [];
  const bats = [];
  const crumbles = [];
  let start = { x: TILE * 2, y: TILE * 14 };
  let flag = { x: TILE * 10, y: TILE * 14 };
  for (let y = 0; y < rows; y++) {
    const row = def.map[y];
    for (let x = 0; x < cols; x++) {
      const ch = row[x];
      const px = x * TILE;
      const py = y * TILE;
      if (ch === '#') grid[y][x] = 1;
      else if (ch === '=') grid[y][x] = 1;
      else if (ch === '~') {
        grid[y][x] = 2;
        crumbles.push({ tx: x, ty: y, x: px, y: py, timer: -1, gone: false });
      } else if (ch === '^') {
        spikes.push({ x: px + 4, y: py + 18, w: TILE - 8, h: TILE - 18 });
      } else if (ch === 'c') {
        coins.push({ x: px + TILE / 2, y: py + TILE / 2, taken: false, bob: x * 0.7 });
      } else if (ch === 'o') {
        shards.push({ x: px + TILE / 2, y: py + TILE / 2, taken: false, bob: y * 1.3 });
      } else if (ch === '*') {
        springs.push({ x: px, y: py, w: TILE, h: 12, anim: 0 });
      } else if (ch === 'C') {
        checkpoints.push({ x: px + TILE / 2, y: py, lit: false });
      } else if (ch === 'F') {
        flag = { x: px + TILE / 2, y: py };
      } else if (ch === 'P') {
        start = { x: px + 5, y: py + 4 };
      } else if (ch === 'W') {
        walkers.push({ x: px + 4, y: py + 8, w: 24, h: 24, dir: -1, speed: 0.7 });
      } else if (ch === 'B') {
        bats.push({ ax: px + TILE / 2, ay: py + TILE / 2, x: px, y: py, w: 26, h: 20, t: x * 1.1 });
      }
    }
  }
  const movers = (def.movers || []).map((m) => ({
    x: m.tx * TILE,
    y: m.ty * TILE,
    w: m.w * TILE,
    h: 12,
    axis: m.axis,
    homeX: m.tx * TILE,
    homeY: m.ty * TILE,
    range: m.range * TILE,
    speed: m.speed,
    t: 0,
    dx: 0,
    dy: 0,
  }));
  return {
    name: def.name,
    palette: def.palette,
    par: def.par,
    grid,
    rows,
    cols,
    width: cols * TILE,
    height: rows * TILE,
    coins,
    shards,
    spikes,
    springs,
    checkpoints,
    walkers,
    bats,
    crumbles,
    movers,
    start,
    flag,
  };
}
